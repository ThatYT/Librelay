type quicJSON = map[string]interface{}

func TestSingboxSelfCertificate(t *testing.T) {
	binary := os.Getenv("LIBRELAY_SINGBOX_TEST_BIN")
	if binary == "" {
		t.Skip("set LIBRELAY_SINGBOX_TEST_BIN")
	}
	// Same command and PEM parser as ensureSelfCert, without writing /etc/gost.
	out, err := exec.Command(binary, "generate", "tls-keypair", "www.bing.com", "--months", "120").CombinedOutput()
	if err != nil {
		t.Fatal("certificate generation failed:", err)
	}
	key, cert := splitPem(string(out))
	pair, err := tls.X509KeyPair([]byte(cert), []byte(key))
	if err != nil {
		t.Fatal("generated certificate/key do not match:", err)
	}
	leaf, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil {
		t.Fatal(err)
	}
	if leaf.VerifyHostname("www.bing.com") != nil || !leaf.NotAfter.After(time.Now().AddDate(9, 0, 0)) {
		t.Fatal("unexpected self-signed certificate name or expiry")
	}
}

// Fixtures are generated by Hysteria2AuditTest using the actual panel builders.
func TestQUICProtocolPaths(t *testing.T) {
	binary, directory := os.Getenv("LIBRELAY_SINGBOX_TEST_BIN"), os.Getenv("LIBRELAY_QUIC_FIXTURES")
	if binary == "" || directory == "" {
		t.Skip("set LIBRELAY_SINGBOX_TEST_BIN and LIBRELAY_QUIC_FIXTURES (Hysteria2AuditTest output)")
	}
	oldConfig, oldLogger := config.Global(), logger.Default()
	config.Set(&config.Config{})
	logger.SetDefault(xlogger.NewLogger(xlogger.OutputOption(io.Discard)))
	defer config.Set(oldConfig)
	if oldLogger != nil {
		defer logger.SetDefault(oldLogger)
	}
	for _, protocol := range []string{"hysteria2", "tuic"} {
		for _, mode := range []string{"public", "legacy"} {
			t.Run(protocol+"-"+mode, func(t *testing.T) {
				testQUICPath(t, binary, filepath.Join(directory, protocol+"-"+mode+".json"), mode == "public")
			})
		}
	}
}
func testQUICPath(t *testing.T, binary, fixture string, public bool) {
	raw, err := os.ReadFile(fixture)
	if err != nil {
		t.Fatal(err)
	}
	var server quicJSON
	if err = json.Unmarshal(raw, &server); err != nil {
		t.Fatal(err)
	}
	inbounds := server["inbounds"].([]interface{})
	inbound := inbounds[0].(map[string]interface{})
	users := inbound["users"].([]interface{})
	user := users[0].(map[string]interface{})
	password, protocol := user["password"].(string), inbound["type"].(string)
	serverPort := quicUDPPort(t)
	inbound["listen_port"] = serverPort
	clientPort := serverPort
	name := "987_7_0_tcp"
	if public {
		gateway, meter := unusedAddress(t), unusedAddress(t)
		_, gatewayPort, _ := net.SplitHostPort(gateway)
		p, _ := strconv.Atoi(gatewayPort)
		inbounds[1].(map[string]interface{})["listen_port"] = p
		_, meterPort, _ := net.SplitHostPort(meter)
		p, _ = strconv.Atoi(meterPort)
		server["outbounds"].([]interface{})[1].(map[string]interface{})["server_port"] = p
		var chain config.ChainConfig
		decodeQUIC(t, quicJSON{"name": "987_7_0_chains", "hops": []interface{}{quicJSON{"name": "gateway-hop", "nodes": []interface{}{quicJSON{
			"name": "gateway", "addr": gateway, "connector": quicJSON{"type": "socks5", "metadata": quicJSON{"notls": true}}, "dialer": quicJSON{"type": "tcp"},
		}}}}}, &chain)
		if err := createChain(createChainRequest{Data: chain}); err != nil {
			t.Fatal(err)
		}
		defer deleteChain(deleteChainRequest{Chain: chain.Name})
		var svc config.ServiceConfig
		decodeQUIC(t, quicJSON{"name": name, "addr": meter, "metadata": quicJSON{"librelay.privateEgress": true},
			"handler": quicJSON{"type": "socks5", "chain": chain.Name, "metadata": quicJSON{"udp": true, "notls": true}}, "listener": quicJSON{"type": "tcp"}}, &svc)
		if err := createServices(createServicesRequest{Data: []config.ServiceConfig{svc}}); err != nil {
			t.Fatal(err)
		}
	} else {
		name = "987_7_0_udp"
		clientPort = quicUDPPort(t)
		var svc config.ServiceConfig
		// GostUtil's legacy UDP handler, listener, keepAlive, and forwarding destination.
		decodeQUIC(t, quicJSON{"name": name, "addr": net.JoinHostPort("127.0.0.1", strconv.Itoa(clientPort)),
			"handler": quicJSON{"type": "udp"}, "listener": quicJSON{"type": "udp", "metadata": quicJSON{"keepAlive": true}},
			"forwarder": quicJSON{"nodes": []interface{}{quicJSON{"name": "node_1", "addr": net.JoinHostPort("127.0.0.1", strconv.Itoa(serverPort))}}}}, &svc)
		if err := createServices(createServicesRequest{Data: []config.ServiceConfig{svc}}); err != nil {
			t.Fatal(err)
		}
	}
	defer deleteServices(deleteServicesRequest{Services: []string{name}})
	meter := registry.ServiceRegistry().Get(name).(interface{ Status() *xservice.Status })
	target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { io.WriteString(w, "quic audit passed") }))
	defer target.Close()
	serverPath := filepath.Join(t.TempDir(), "server.json")
	startServer := func() func() { writeQUIC(t, serverPath, server); return startQUICRuntime(t, binary, serverPath) }
	stop := startServer()
	defer func() { stop() }()
	request := func(host, credential string, wantOK bool) {
		t.Helper()
		address := unusedAddress(t)
		mixedHost, mixedPort, _ := net.SplitHostPort(address)
		port, _ := strconv.Atoi(mixedPort)
		outbound := quicJSON{"type": protocol, "server": host, "server_port": clientPort, "password": credential,
			"tls": quicJSON{"enabled": true, "insecure": true, "server_name": "www.bing.com"}}
		if protocol == "tuic" {
			outbound["uuid"] = user["uuid"]
			outbound["congestion_control"] = "bbr"
			outbound["tls"].(map[string]interface{})["alpn"] = []string{"h3"}
		}
		client := quicJSON{"log": quicJSON{"disabled": true}, "inbounds": []interface{}{quicJSON{"type": "mixed", "listen": mixedHost, "listen_port": port}}, "outbounds": []interface{}{outbound}}
		path := filepath.Join(t.TempDir(), "client.json")
		writeQUIC(t, path, client)
		stopClient := startQUICRuntime(t, binary, path)
		defer stopClient()
		dialer, err := proxy.SOCKS5("tcp", address, nil, &net.Dialer{Timeout: 3 * time.Second})
		if err != nil {
			t.Fatal(err)
		}
		transport := &http.Transport{Dial: dialer.Dial}
		defer transport.CloseIdleConnections()
		httpClient := &http.Client{Transport: transport, Timeout: 3 * time.Second}
		response, err := httpClient.Get(target.URL)
		if !wantOK {
			if err == nil {
				response.Body.Close()
				t.Fatal("invalid/revoked credentials accepted")
			}
			return
		}
		if err != nil {
			t.Fatalf("QUIC path failed: %v", err)
		}
		defer response.Body.Close()
		body, err := io.ReadAll(response.Body)
		if err != nil || string(body) != "quic audit passed" {
			t.Fatal("incorrect QUIC response")
		}
	}
	request("127.0.0.1", password, true)
	if public {
		request("::1", password, true)
	}
	request("127.0.0.1", password+"-invalid", false)
	stop()
	inbound["users"] = []interface{}{}
	stop = startServer()
	request("127.0.0.1", password, false)
	stop()
	inbound["users"] = users
	stop = startServer()
	request("127.0.0.1", password, true)
	if meter.Status().Stats().Get(stats.KindInputBytes) <= 0 || meter.Status().Stats().Get(stats.KindOutputBytes) <= 0 {
		t.Fatal("QUIC path did not account traffic in GOST")
	}
}
func quicUDPPort(t *testing.T) int {
	t.Helper()
	listener, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Close()
	return listener.LocalAddr().(*net.UDPAddr).Port
}
func decodeQUIC(t *testing.T, value, destination interface{}) {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, destination); err != nil {
		t.Fatal(err)
	}
}
func writeQUIC(t *testing.T, path string, value interface{}) {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, raw, 0600); err != nil {
		t.Fatal(err)
	}
}
func startQUICRuntime(t *testing.T, binary, path string) func() {
	t.Helper()
	if err := exec.Command(binary, "check", "-c", path).Run(); err != nil {
		t.Fatal("sing-box rejected generated configuration:", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cmd := exec.CommandContext(ctx, binary, "run", "-c", path)
	// Do not print runtime configuration or credentials in test output.
	if err := cmd.Start(); err != nil {
		cancel()
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()
	select {
	case <-done:
		cancel()
		t.Fatal("sing-box exited during startup")
	case <-time.After(250 * time.Millisecond):
	}
	stopped := false
	stop := func() {
		if !stopped {
			stopped = true
			cancel()
			<-done
		}
	}
	t.Cleanup(stop)
	return stop
}

// Optional check against an installed Mihomo core, using the unmodified YAML proxy export.
func TestMihomoHY2Export(t *testing.T) {
	binary, directory, mihomo := os.Getenv("LIBRELAY_SINGBOX_TEST_BIN"), os.Getenv("LIBRELAY_QUIC_FIXTURES"), os.Getenv("LIBRELAY_MIHOMO_TEST_BIN")
	if binary == "" || directory == "" || mihomo == "" {
		t.Skip("set sing-box, fixture directory and LIBRELAY_MIHOMO_TEST_BIN")
	}
	raw, err := os.ReadFile(filepath.Join(directory, "hysteria2-legacy.json"))
	if err != nil {
		t.Fatal(err)
	}
	var server quicJSON
	if err := json.Unmarshal(raw, &server); err != nil {
		t.Fatal(err)
	}
	port := quicUDPPort(t)
	server["inbounds"].([]interface{})[0].(map[string]interface{})["listen_port"] = port
	serverPath := filepath.Join(t.TempDir(), "server.json")
	writeQUIC(t, serverPath, server)
	stop := startQUICRuntime(t, binary, serverPath)
	defer stop()
	raw, err = os.ReadFile(filepath.Join(directory, "mihomo.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	var client quicJSON
	if err := yaml.Unmarshal(raw, &client); err != nil {
		t.Fatal(err)
	}
	client["proxies"].([]interface{})[0].(map[string]interface{})["port"] = port
	address := unusedAddress(t)
	_, mixedPort, _ := net.SplitHostPort(address)
	client["mixed-port"], _ = strconv.Atoi(mixedPort)
	dir := t.TempDir()
	path := filepath.Join(dir, "config.yaml")
	raw, err = yaml.Marshal(client)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, raw, 0600); err != nil {
		t.Fatal(err)
	}
	if err := exec.Command(mihomo, "-t", "-d", dir, "-f", path).Run(); err != nil {
		t.Fatal("Mihomo rejected YAML export:", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	cmd := exec.CommandContext(ctx, mihomo, "-d", dir, "-f", path)
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	defer func() { cancel(); cmd.Wait() }()
	target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { io.WriteString(w, "mihomo export passed") }))
	defer target.Close()
	// Wait for the client listener rather than querying any production endpoint.
	deadline := time.Now().Add(3 * time.Second)
	for {
		conn, err := net.DialTimeout("tcp", address, 100*time.Millisecond)
		if err == nil {
			conn.Close()
			// Allow client initialization to finish before opening a proxy session.
			time.Sleep(250 * time.Millisecond)
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("Mihomo listener did not start")
		}
		time.Sleep(25 * time.Millisecond)
	}
	dialer, err := proxy.SOCKS5("tcp", address, nil, &net.Dialer{Timeout: 3 * time.Second})
	if err != nil {
		t.Fatal(err)
	}
	transport := &http.Transport{Dial: dialer.Dial}
	defer transport.CloseIdleConnections()
	httpClient := &http.Client{Transport: transport, Timeout: 3 * time.Second}
	response, err := httpClient.Get(target.URL)
	if err != nil {
		t.Fatalf("Mihomo HY2 export failed: %v", err)
	}
	defer response.Body.Close()
	body, err := io.ReadAll(response.Body)
	if err != nil || string(body) != "mihomo export passed" {
		t.Fatal("incorrect Mihomo response")
	}
}
