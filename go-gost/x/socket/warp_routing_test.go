// Fixtures are generated by WarpRoutingTest using the actual panel builders.
func TestWarpRoutingPaths(t *testing.T) {
	binary, directory := os.Getenv("LIBRELAY_SINGBOX_TEST_BIN"), os.Getenv("LIBRELAY_WARP_FIXTURES")
	if binary == "" || directory == "" {
		t.Skip("set LIBRELAY_SINGBOX_TEST_BIN and LIBRELAY_WARP_FIXTURES (WarpRoutingTest output)")
	}
	oldConfig, oldLogger := config.Global(), logger.Default()
	config.Set(&config.Config{})
	logger.SetDefault(xlogger.NewLogger(xlogger.OutputOption(io.Discard)))
	defer config.Set(oldConfig)
	if oldLogger != nil {
		defer logger.SetDefault(oldLogger)
	}
	for _, protocol := range []string{"hysteria2", "tuic"} {
		for _, mode := range []string{"public", "legacy"} {
			t.Run(protocol+"-"+mode, func(t *testing.T) {
				testWarpPath(t, binary, filepath.Join(directory, protocol+"-"+mode+".json"), mode == "public")
			})
		}
	}
}
func testWarpPath(t *testing.T, binary, fixture string, public bool) {
	raw, err := os.ReadFile(fixture)
	if err != nil {
		t.Fatal(err)
	}
	var server warpJSON
	if err = json.Unmarshal(raw, &server); err != nil {
		t.Fatal(err)
	}
	// Make the matching hostname resolvable natively too, so a fallback bug cannot
	// hide behind a DNS failure. This hosts resolver exists only in test fixtures.
	server["dns"] = warpJSON{"servers": []interface{}{warpJSON{"type": "hosts", "tag": "fixture-hosts", "predefined": warpJSON{"warp.test": "127.0.0.1"}}}}
	for _, value := range server["outbounds"].([]interface{}) {
		outbound := value.(map[string]interface{})
		if outbound["tag"] == "direct" {
			outbound["domain_resolver"] = "fixture-hosts"
		}
	}
	inbounds := server["inbounds"].([]interface{})
	inbound := inbounds[0].(map[string]interface{})
	user := inbound["users"].([]interface{})[0].(map[string]interface{})
	password, protocol := user["password"].(string), inbound["type"].(string)
	serverPort := warpUDPPort(t)
	inbound["listen_port"] = serverPort
	clientPort := serverPort
	name := "987_7_0_tcp"
	if public {
		gateway, meter := unusedAddress(t), unusedAddress(t)
		_, gatewayPort, _ := net.SplitHostPort(gateway)
		p, _ := strconv.Atoi(gatewayPort)
		inbounds[1].(map[string]interface{})["listen_port"] = p
		_, meterPort, _ := net.SplitHostPort(meter)
		p, _ = strconv.Atoi(meterPort)
		for _, value := range server["outbounds"].([]interface{}) {
			outbound := value.(map[string]interface{})
			if outbound["tag"] == "meter-3" {
				outbound["server_port"] = p
			}
		}
		var chain config.ChainConfig
		decodeWarp(t, warpJSON{"name": "987_7_0_chains", "hops": []interface{}{warpJSON{"name": "gateway-hop", "nodes": []interface{}{warpJSON{
			"name": "gateway", "addr": gateway, "connector": warpJSON{"type": "socks5", "metadata": warpJSON{"notls": true, "relay": "udp"}}, "dialer": warpJSON{"type": "tcp"},
		}}}}}, &chain)
		if err := createChain(createChainRequest{Data: chain}); err != nil {
			t.Fatal(err)
		}
		defer deleteChain(deleteChainRequest{Chain: chain.Name})
		var svc config.ServiceConfig
		decodeWarp(t, warpJSON{"name": name, "addr": meter, "metadata": warpJSON{"librelay.privateEgress": true},
			"handler": warpJSON{"type": "socks5", "chain": chain.Name, "metadata": warpJSON{"udp": true, "notls": true}}, "listener": warpJSON{"type": "tcp"}}, &svc)
		if err := createServices(createServicesRequest{Data: []config.ServiceConfig{svc}}); err != nil {
			t.Fatal(err)
		}
	} else {
		name = "987_7_0_udp"
		clientPort = warpUDPPort(t)
		var svc config.ServiceConfig
		// GostUtil's legacy UDP handler, listener, keepAlive, and forwarding destination.
		decodeWarp(t, warpJSON{"name": name, "addr": net.JoinHostPort("127.0.0.1", strconv.Itoa(clientPort)),
			"handler": warpJSON{"type": "udp"}, "listener": warpJSON{"type": "udp", "metadata": warpJSON{"keepAlive": true}},
			"forwarder": warpJSON{"nodes": []interface{}{warpJSON{"name": "node_1", "addr": net.JoinHostPort("127.0.0.1", strconv.Itoa(serverPort))}}}}, &svc)
		if err := createServices(createServicesRequest{Data: []config.ServiceConfig{svc}}); err != nil {
			t.Fatal(err)
		}
	}
	defer deleteServices(deleteServicesRequest{Services: []string{name}})
	meter := registry.ServiceRegistry().Get(name).(interface{ Status() *xservice.Status })
	target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { io.WriteString(w, "warp audit passed") }))
	defer target.Close()
	var warpRequests atomic.Int32
	warpAddress, stopWarp := startWarpProxy(t, "127.0.0.1:0", target.Listener.Addr().String(), &warpRequests)
	defer func() { stopWarp() }()
	_, warpPort, _ := net.SplitHostPort(warpAddress)
	warpPortNumber, _ := strconv.Atoi(warpPort)
	for _, value := range server["outbounds"].([]interface{}) {
		outbound := value.(map[string]interface{})
		if outbound["tag"] == "warp-google" {
			outbound["server_port"] = warpPortNumber
		}
	}
	serverPath := filepath.Join(t.TempDir(), "server.json")
	startServer := func() func() { writeWarp(t, serverPath, server); return startWarpRuntime(t, binary, serverPath) }
	stop := startServer()
	defer func() { stop() }()
	udpChecked := false
	request := func(host, credential, targetURL string, wantOK bool) {
		t.Helper()
		address := unusedAddress(t)
		mixedHost, mixedPort, _ := net.SplitHostPort(address)
		port, _ := strconv.Atoi(mixedPort)
		outbound := warpJSON{"type": protocol, "server": host, "server_port": clientPort, "password": credential,
			"tls": warpJSON{"enabled": true, "insecure": true, "server_name": "www.bing.com"}}
		if protocol == "tuic" {
			outbound["uuid"] = user["uuid"]
			outbound["congestion_control"] = "bbr"
			outbound["tls"].(map[string]interface{})["alpn"] = []string{"h3"}
		}
		client := warpJSON{"log": warpJSON{"disabled": true}, "inbounds": []interface{}{warpJSON{"type": "mixed", "listen": mixedHost, "listen_port": port}}, "outbounds": []interface{}{outbound}}
		path := filepath.Join(t.TempDir(), "client.json")
		writeWarp(t, path, client)
		stopClient := startWarpRuntime(t, binary, path)
		defer stopClient()
		dialer, err := proxy.SOCKS5("tcp", address, nil, &net.Dialer{Timeout: 3 * time.Second})
		if err != nil {
			t.Fatal(err)
		}
		transport := &http.Transport{Dial: dialer.Dial}
		defer transport.CloseIdleConnections()
		httpClient := &http.Client{Transport: transport, Timeout: 3 * time.Second}
		response, err := httpClient.Get(targetURL)
		if !wantOK {
			if err == nil {
				response.Body.Close()
				t.Fatal("invalid/revoked credentials accepted")
			}
			return
		}
		if err != nil {
			t.Fatalf("Warp path failed: %v", err)
		}
		defer response.Body.Close()
		body, err := io.ReadAll(response.Body)
		if err != nil || string(body) != "warp audit passed" {
			t.Fatal("incorrect WARP response")
		}
		if !udpChecked {
			testWarpUDP(t, address)
			udpChecked = true
		}
	}
	_, targetPort, _ := net.SplitHostPort(target.Listener.Addr().String())
	matched := "http://warp.test:" + targetPort
	request("127.0.0.1", password, matched, true)
	if warpRequests.Load() != 1 {
		t.Fatal("matching hostname did not reach WARP proxy")
	}
	if public {
		request("::1", password, matched, true)
	}
	baseline := warpRequests.Load()
	request("127.0.0.1", password, target.URL, true)
	if warpRequests.Load() != baseline {
		t.Fatal("unrelated traffic used WARP")
	}
	request("127.0.0.1", password+"-invalid", matched, false)
	if warpRequests.Load() != baseline {
		t.Fatal("unauthenticated traffic reached WARP")
	}
	stopWarp()
	request("127.0.0.1", password, matched, false)
	request("127.0.0.1", password, target.URL, true)
	_, stopWarp = startWarpProxy(t, warpAddress, target.Listener.Addr().String(), &warpRequests)
	stop()
	stop = startServer()
	request("127.0.0.1", password, matched, true)
	if warpRequests.Load() != baseline+1 {
		t.Fatal("restart lost WARP routing")
	}

	// Control: removing only the TCP WARP rule must make that same hostname work
	// through direct even while the WARP proxy is unavailable.
	stopWarp()
	rules := server["route"].(map[string]interface{})["rules"].([]interface{})
	kept := make([]interface{}, 0, len(rules))
	for _, value := range rules {
		if value.(map[string]interface{})["outbound"] != "warp-google" {
			kept = append(kept, value)
		}
	}
	server["route"].(map[string]interface{})["rules"] = kept
	stop()
	stop = startServer()
	request("127.0.0.1", password, matched, true)
	if meter.Status().Stats().Get(stats.KindInputBytes) <= 0 || meter.Status().Stats().Get(stats.KindOutputBytes) <= 0 {
		t.Fatal("Warp path did not account traffic in GOST")
	}
}
func warpUDPPort(t *testing.T) int {
	t.Helper()
	listener, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Close()
	return listener.LocalAddr().(*net.UDPAddr).Port
}
func decodeWarp(t *testing.T, value, destination interface{}) {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, destination); err != nil {
		t.Fatal(err)
	}
}
func writeWarp(t *testing.T, path string, value interface{}) {
	t.Helper()
	raw, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, raw, 0600); err != nil {
		t.Fatal(err)
	}
}
func startWarpRuntime(t *testing.T, binary, path string) func() {
	t.Helper()
	if err := exec.Command(binary, "check", "-c", path).Run(); err != nil {
		t.Fatal("sing-box rejected generated configuration:", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cmd := exec.CommandContext(ctx, binary, "run", "-c", path)
	// Do not print runtime configuration or credentials in test output.
	if err := cmd.Start(); err != nil {
		cancel()
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()
	select {
	case <-done:
		cancel()
		t.Fatal("sing-box exited during startup")
	case <-time.After(250 * time.Millisecond):
	}
	stopped := false
	stop := func() {
		if !stopped {
			stopped = true
			cancel()
			<-done
		}
	}
	t.Cleanup(stop)
	return stop
}

// A local stand-in for the existing WARP SOCKS endpoint; receives unresolved hostnames.
func startWarpProxy(t *testing.T, address, target string, requests *atomic.Int32) (string, func()) {
	t.Helper()
	listener, err := net.Listen("tcp", address)
	if err != nil {
		t.Fatal(err)
	}
	go func() {
		for {
			conn, err := listener.Accept()
			if err != nil {
				return
			}
			go func() {
				defer conn.Close()
				conn.SetDeadline(time.Now().Add(5 * time.Second))
				header := make([]byte, 2)
				if _, err := io.ReadFull(conn, header); err != nil {
					return
				}
				methods := make([]byte, int(header[1]))
				if _, err := io.ReadFull(conn, methods); err != nil {
					return
				}
				conn.Write([]byte{5, 0})
				request, err := gosocks5.ReadRequest(conn)
				if err != nil {
					return
				}
				if request.Cmd != gosocks5.CmdConnect || request.Addr.Host != "warp.test" {
					return
				}
				requests.Add(1)
				upstream, err := net.DialTimeout("tcp", target, time.Second)
				if err != nil {
					return
				}
				defer upstream.Close()
				conn.Write([]byte{5, 0, 0, 1, 127, 0, 0, 1, 0, 0})
				go io.Copy(upstream, conn)
				io.Copy(conn, upstream)
			}()
		}
	}()
	var stopped bool
	stop := func() {
		if !stopped {
			stopped = true
			listener.Close()
		}
	}
	t.Cleanup(stop)
	return listener.Addr().String(), stop
}

// Matching UDP must be rejected while unrelated UDP still traverses the meter.
func testWarpUDP(t *testing.T, socksAddress string) {
	t.Helper()
	echo, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer echo.Close()
	go func() {
		buffer := make([]byte, 1024)
		for {
			n, source, err := echo.ReadFrom(buffer)
			if err != nil {
				return
			}
			echo.WriteTo(buffer[:n], source)
		}
	}()
	control, err := net.DialTimeout("tcp", socksAddress, time.Second)
	if err != nil {
		t.Fatal(err)
	}
	defer control.Close()
	control.SetDeadline(time.Now().Add(5 * time.Second))
	control.Write([]byte{5, 1, 0})
	greeting := make([]byte, 2)
	if _, err := io.ReadFull(control, greeting); err != nil {
		t.Fatal(err)
	}
	address, _ := gosocks5.NewAddr("0.0.0.0:0")
	if err := gosocks5.NewRequest(gosocks5.CmdUdp, address).Write(control); err != nil {
		t.Fatal(err)
	}
	reply, err := gosocks5.ReadReply(control)
	if err != nil || reply.Rep != gosocks5.Succeeded {
		t.Fatal("client UDP association failed")
	}
	udpAddress, err := net.ResolveUDPAddr("udp", reply.Addr.String())
	if err != nil {
		t.Fatal(err)
	}
	udp, err := net.DialUDP("udp", nil, udpAddress)
	if err != nil {
		t.Fatal(err)
	}
	defer udp.Close()
	_, port, _ := net.SplitHostPort(echo.LocalAddr().String())
	send := func(host string, wantReply bool) {
		destination, _ := gosocks5.NewAddr(net.JoinHostPort(host, port))
		datagram := gosocks5.NewUDPDatagram(gosocks5.NewUDPHeader(0, 0, destination), []byte("warp udp check"))
		var packet bytes.Buffer
		datagram.WriteTo(&packet)
		udp.SetDeadline(time.Now().Add(time.Second))
		udp.Write(packet.Bytes())
		buffer := make([]byte, 1024)
		n, err := udp.Read(buffer)
		if !wantReply {
			if err == nil {
				t.Fatal("matching UDP leaked to native exit")
			}
			return
		}
		if err != nil {
			t.Fatal("unrelated UDP failed:", err)
		}
		result := &gosocks5.UDPDatagram{}
		if _, err := result.ReadFrom(bytes.NewReader(buffer[:n])); err != nil || string(result.Data) != "warp udp check" {
			t.Fatal("incorrect UDP echo")
		}
	}
	send("warp.test", false)
	send("127.0.0.1", true)
}
